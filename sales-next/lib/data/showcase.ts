const DAY = 24 * 60 * 60 * 1000;
const iso = (now: Date, daysAgo: number) => new Date(now.getTime() - daysAgo * DAY).toISOString();
const isoFuture = (now: Date, days: number) => new Date(now.getTime() + days * DAY).toISOString();

function seg(lines: [string, string][]): TranscriptSegment[] {
  let t = 0;
  return lines.map(([speaker, text]) => {
    const s = { t, speaker, text };
    t += 8 + Math.min(22, Math.round(text.length / 3));
    return s;
  });
}

